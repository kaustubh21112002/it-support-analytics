-- =====================================================================
-- IT Support Ticket Analysis & Service Performance Dashboard
-- Supabase Schema Controlled Rebuild Script
-- =====================================================================
-- WARNING: DESTRUCTIVE ACTION FOR THE SIX NAMED TABLES
-- This script explicitly DROPS and RECREATES the six IT Support Analytics
-- tables to correct column data types from TEXT to INTEGER identity keys.
--
-- TARGET TABLES DROPPED & RECREATED:
--   1. tickets
--   2. agents
--   3. teams
--   4. departments
--   5. categories
--   6. sla_rules
--
-- BEFORE RUNNING:
--   Ensure any necessary table backups have been taken. The five existing
--   records in `departments` will be removed by this rebuild and must be
--   re-ingested from `it_support_analytics_dataset/data/departments.csv`.
--
-- SAFETY CONSTRAINTS ENFORCED:
--   - NO CASCADE is used on DROP statements. If any external view, table,
--     or trigger outside these six tables depends on them, PostgreSQL
--     will halt execution with a dependency notice rather than dropping
--     unintended objects.
--   - Custom ENUM types are NOT dropped. They are safely preserved so
--     other database objects are not affected.
--   - Sequence synchronization statements are NOT included in this file
--     (run sequence synchronization only AFTER importing CSV data).
-- =====================================================================


-- =====================================================================
-- 1. Safe Drop of Existing Tables (Strict Reverse Dependency Order)
-- =====================================================================
-- Dropping in reverse dependency order avoids foreign-key constraint
-- errors without requiring the CASCADE clause.

DROP TABLE IF EXISTS tickets;
DROP TABLE IF EXISTS agents;
DROP TABLE IF EXISTS teams;
DROP TABLE IF EXISTS departments;
DROP TABLE IF EXISTS categories;
DROP TABLE IF EXISTS sla_rules;


-- =====================================================================
-- 2. Preserve / Verify Custom Enum Types
-- =====================================================================
-- Custom types are NOT dropped. These defensive blocks verify existence
-- and create them only if they are missing, ensuring idempotency without
-- disrupting existing dependencies.

DO $$ BEGIN
    CREATE TYPE ticket_priority AS ENUM ('Critical', 'High', 'Medium', 'Low');
EXCEPTION
    WHEN duplicate_object THEN NULL;
END $$;

DO $$ BEGIN
    CREATE TYPE ticket_status AS ENUM ('Open', 'In Progress', 'Pending', 'Resolved', 'Closed');
EXCEPTION
    WHEN duplicate_object THEN NULL;
END $$;

DO $$ BEGIN
    CREATE TYPE agent_experience_band AS ENUM ('Junior', 'Mid-level', 'Senior');
EXCEPTION
    WHEN duplicate_object THEN NULL;
END $$;


-- =====================================================================
-- 3. Dependency-Safe Table Creation
-- =====================================================================

-- Table 1: departments
-- Independent dimension table housing business departments.
CREATE TABLE departments (
    department_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_name VARCHAR(100) NOT NULL UNIQUE,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- Table 2: categories
-- Independent dimension table housing ITIL request categories and subcategories.
CREATE TABLE categories (
    category_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name VARCHAR(100) NOT NULL,
    subcategory_name VARCHAR(150) NOT NULL,
    CONSTRAINT uq_category_sub UNIQUE (category_name, subcategory_name)
);

-- Table 3: sla_rules
-- Independent dimension table defining calendar-hour SLA thresholds.
CREATE TABLE sla_rules (
    sla_rule_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    priority ticket_priority NOT NULL UNIQUE,
    target_resolution_hours DECIMAL(6,2) NOT NULL,
    description VARCHAR(255) NULL
);

-- Table 4: teams
-- Operational support teams referencing corporate departments.
-- Foreign key dependency: departments(department_id)
CREATE TABLE teams (
    team_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_name VARCHAR(100) NOT NULL,
    department_id INTEGER NOT NULL,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_teams_department FOREIGN KEY (department_id)
        REFERENCES departments (department_id)
        ON DELETE RESTRICT
        ON UPDATE CASCADE
);

-- Table 5: agents
-- Support specialists assigned to tickets, referencing support teams.
-- Foreign key dependency: teams(team_id)
CREATE TABLE agents (
    agent_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agent_code VARCHAR(20) NOT NULL UNIQUE,
    agent_name VARCHAR(100) NOT NULL,
    team_id INTEGER NOT NULL,
    experience_band agent_experience_band NOT NULL DEFAULT 'Mid-level',
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_agents_team FOREIGN KEY (team_id)
        REFERENCES teams (team_id)
        ON DELETE RESTRICT
        ON UPDATE CASCADE
);

-- Table 6: tickets
-- Core fact table containing 8,000 incident transactions.
-- Foreign key dependencies: categories, departments, teams, agents, sla_rules.
CREATE TABLE tickets (
    ticket_id VARCHAR(20) PRIMARY KEY,
    created_at TIMESTAMP NOT NULL,
    resolved_at TIMESTAMP NULL,
    status ticket_status NOT NULL DEFAULT 'Open',
    priority ticket_priority NOT NULL,
    category_id INTEGER NOT NULL,
    issue_type VARCHAR(150) NOT NULL,
    department_id INTEGER NOT NULL,
    team_id INTEGER NOT NULL,
    agent_id INTEGER NULL,
    sla_rule_id INTEGER NOT NULL,
    satisfaction_rating SMALLINT NULL CHECK (satisfaction_rating BETWEEN 1 AND 5),
    resolution_time_hours DECIMAL(8,2) NULL,
    CONSTRAINT fk_tickets_category FOREIGN KEY (category_id)
        REFERENCES categories (category_id),
    CONSTRAINT fk_tickets_department FOREIGN KEY (department_id)
        REFERENCES departments (department_id),
    CONSTRAINT fk_tickets_team FOREIGN KEY (team_id)
        REFERENCES teams (team_id),
    CONSTRAINT fk_tickets_agent FOREIGN KEY (agent_id)
        REFERENCES agents (agent_id),
    CONSTRAINT fk_tickets_sla_rule FOREIGN KEY (sla_rule_id)
        REFERENCES sla_rules (sla_rule_id)
);


-- =====================================================================
-- 4. Performance Indexes
-- =====================================================================
-- Indexes mirroring the original relational design for high-throughput
-- analytical filtering and dashboard queries.

CREATE INDEX idx_tickets_created_at ON tickets (created_at);
CREATE INDEX idx_tickets_status ON tickets (status);
CREATE INDEX idx_tickets_priority ON tickets (priority);
CREATE INDEX idx_tickets_category_id ON tickets (category_id);
CREATE INDEX idx_tickets_department_id ON tickets (department_id);
CREATE INDEX idx_tickets_team_id ON tickets (team_id);
CREATE INDEX idx_tickets_agent_id ON tickets (agent_id);
