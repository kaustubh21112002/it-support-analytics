-- =====================================================================
-- 1. Custom Enum Types
-- =====================================================================
-- Using defensive blocks so script can be safely re-run without errors.

DO $$ BEGIN
    CREATE TYPE ticket_priority AS ENUM ('Critical', 'High', 'Medium', 'Low');
EXCEPTION
    WHEN duplicate_object THEN NULL;
END $$;

DO $$ BEGIN
    CREATE TYPE ticket_status AS ENUM ('Open', 'In Progress', 'Pending', 'Resolved', 'Closed');
EXCEPTION
    WHEN duplicate_object THEN NULL;
END $$;

DO $$ BEGIN
    CREATE TYPE agent_experience_band AS ENUM ('Junior', 'Mid-level', 'Senior');
EXCEPTION
    WHEN duplicate_object THEN NULL;
END $$;


-- =====================================================================
-- 2. Dimension Tables
-- =====================================================================

-- Table 1: departments
-- Houses corporate business units originating support requests.
CREATE TABLE IF NOT EXISTS departments (
    department_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_name VARCHAR(100) NOT NULL UNIQUE,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- Table 2: categories
-- Standardized ITIL request classifications and subcategories.
CREATE TABLE IF NOT EXISTS categories (
    category_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name VARCHAR(100) NOT NULL,
    subcategory_name VARCHAR(150) NOT NULL,
    CONSTRAINT uq_category_sub UNIQUE (category_name, subcategory_name)
);

-- Table 3: sla_rules
-- Governed SLA turnaround thresholds (calendar-hour basis).
CREATE TABLE IF NOT EXISTS sla_rules (
    sla_rule_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    priority ticket_priority NOT NULL UNIQUE,
    target_resolution_hours DECIMAL(6,2) NOT NULL,
    description VARCHAR(255) NULL
);

-- Table 4: teams
-- Operational support tiers and specialized technical service teams.
-- Foreign key dependency: departments(department_id)
CREATE TABLE IF NOT EXISTS teams (
    team_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_name VARCHAR(100) NOT NULL,
    department_id INTEGER NOT NULL,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_teams_department FOREIGN KEY (department_id)
        REFERENCES departments (department_id)
        ON DELETE RESTRICT
        ON UPDATE CASCADE
);

-- Table 5: agents
-- Support specialists assigned to resolve incident tickets.
-- Foreign key dependency: teams(team_id)
-- Cryptographic identity mapping: user_id references auth.users(id) (Model C Hybrid Authorization)
CREATE TABLE IF NOT EXISTS agents (
    agent_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agent_code VARCHAR(20) NOT NULL UNIQUE,
    agent_name VARCHAR(100) NOT NULL,
    team_id INTEGER NOT NULL,
    experience_band agent_experience_band NOT NULL DEFAULT 'Mid-level',
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP NOT NULL,
    user_id UUID NULL UNIQUE,
    CONSTRAINT fk_agents_team FOREIGN KEY (team_id)
        REFERENCES teams (team_id)
        ON DELETE RESTRICT
        ON UPDATE CASCADE,
    CONSTRAINT fk_agents_user FOREIGN KEY (user_id)
        REFERENCES auth.users (id)
        ON DELETE SET NULL
);

-- Table 5.1: agent_directory (Public-Safe Dimension Projection)
-- Excludes internal cryptographic user_id identity mapping to prevent
-- harvesting auth UUIDs across anonymous and standard authenticated sessions.
CREATE OR REPLACE VIEW public.agent_directory AS
SELECT
    agent_id,
    agent_code,
    agent_name,
    team_id,
    experience_band,
    is_active,
    created_at
FROM public.agents;

ALTER VIEW public.agent_directory OWNER TO postgres;

-- Public-Safe Agent Directory View Grants:
-- Standard client applications, UI dashboards, and anonymous demo visitors
-- need agent directory data but must never see internal user_id mapping UUIDs.
REVOKE ALL ON TABLE public.agent_directory FROM PUBLIC;
GRANT SELECT ON TABLE public.agent_directory TO anon, authenticated;
GRANT ALL ON TABLE public.agent_directory TO service_role;



-- =====================================================================
-- 3. Core Fact Table
-- =====================================================================

-- Table 6: tickets
-- Granular incident and service request fact records (8,000 baseline).
-- Foreign key dependencies: categories, departments, teams, agents, sla_rules.
CREATE TABLE IF NOT EXISTS tickets (
    ticket_id VARCHAR(20) PRIMARY KEY,
    created_at TIMESTAMP NOT NULL,
    resolved_at TIMESTAMP NULL,
    status ticket_status NOT NULL DEFAULT 'Open',
    priority ticket_priority NOT NULL,
    category_id INTEGER NOT NULL,
    issue_type VARCHAR(150) NOT NULL,
    department_id INTEGER NOT NULL,
    team_id INTEGER NOT NULL,
    agent_id INTEGER NULL,
    sla_rule_id INTEGER NOT NULL,
    satisfaction_rating SMALLINT NULL CHECK (satisfaction_rating BETWEEN 1 AND 5),
    resolution_time_hours DECIMAL(8,2) NULL,
    CONSTRAINT fk_tickets_category FOREIGN KEY (category_id)
        REFERENCES categories (category_id),
    CONSTRAINT fk_tickets_department FOREIGN KEY (department_id)
        REFERENCES departments (department_id),
    CONSTRAINT fk_tickets_team FOREIGN KEY (team_id)
        REFERENCES teams (team_id),
    CONSTRAINT fk_tickets_agent FOREIGN KEY (agent_id)
        REFERENCES agents (agent_id),
    CONSTRAINT fk_tickets_sla_rule FOREIGN KEY (sla_rule_id)
        REFERENCES sla_rules (sla_rule_id)
);


-- =====================================================================
-- 4. Performance Indexes
-- =====================================================================
-- Corresponds to MySQL DDL indexes, adapted for PostgreSQL.

CREATE INDEX IF NOT EXISTS idx_tickets_created_at ON tickets (created_at);
CREATE INDEX IF NOT EXISTS idx_tickets_status ON tickets (status);
CREATE INDEX IF NOT EXISTS idx_tickets_priority ON tickets (priority);
CREATE INDEX IF NOT EXISTS idx_tickets_category_id ON tickets (category_id);
CREATE INDEX IF NOT EXISTS idx_tickets_department_id ON tickets (department_id);
CREATE INDEX IF NOT EXISTS idx_tickets_team_id ON tickets (team_id);
CREATE INDEX IF NOT EXISTS idx_tickets_agent_id ON tickets (agent_id);


